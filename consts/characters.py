import random

def get_random_character():
    # 全キャラの全セリフをキャラごとに展開し、重み付きランダムにする
    all_entries = []
    for char in CHARACTERS_LIST:
        name = char["name"]
        cid = char["id"]
        for msg in CHARACTERS_MESSAGE[name]:
            all_entries.append({"id": cid, "name": name, "messages": msg})
    return random.choice(all_entries)